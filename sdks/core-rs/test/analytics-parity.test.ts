// Analytics parity between the web and Flutter SDKs: the same inputs through
// this package's createTryOnAnalytics must send the requests that
// sdks/flutter/test/analytics_parity/expected.json records, and the Flutter
// SDK's own createTryOnAnalytics checks the same file
// (sdks/flutter/test/analytics_parity_test.dart). Regenerate the file from the
// web's mapper with UPDATE_ANALYTICS_PARITY=1.
import type { TryOnExperienceEvent } from "@studio-vaai/core";

import { initializeCore } from "@studio-vaai/core";
import { createTryOnAnalytics } from "@studio-vaai/core/analytics";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";

const parity = resolve(import.meta.dirname, "../../flutter/test/analytics_parity");

type Operation =
  | { op: "event"; event: TryOnExperienceEvent }
  | { op: "entrypointImpression"; productId: string; entry: string }
  | { op: "cartItemAdded" | "orderPlaced"; productId: string; foreignIds: Record<string, string> }
  | { op: "experimentAssigned"; enabled: boolean }
  | { op: "enabled"; value: boolean };

interface Input {
  visitorId: string;
  sdkVersion: string;
  clientApiKey: string;
  baseUrl: string;
  operations: Operation[];
}

interface Sent {
  method: string;
  path: string;
  clientApiKey: string | null;
  body: unknown;
}

async function settle(): Promise<void> {
  // oxlint-disable-next-line eslint-plugin-promise/avoid-new -- A macrotask lets each delivery finish.
  await new Promise((resolve) => {
    setTimeout(resolve, 10);
  });
}

describe("analytics parity with the Flutter SDK", () => {
  beforeAll(async () => {
    await initializeCore(
      new Uint8Array(await readFile(resolve(import.meta.dirname, "../dist/studio_vaai_core.wasm"))),
    );
  });

  it("sends the requests expected.json records for input.json", async () => {
    const input = JSON.parse(await readFile(`${parity}/input.json`, "utf8")) as Input;
    const sent: Sent[] = [];
    let enabled = true;
    const analytics = createTryOnAnalytics({
      clientApiKey: input.clientApiKey,
      baseUrl: input.baseUrl,
      sdkVersion: input.sdkVersion,
      enabled: () => enabled,
      visitorId: () => input.visitorId,
      fetch: async (resource, init) => {
        const request = new Request(resource, init);
        sent.push({
          method: request.method,
          path: new URL(request.url).pathname,
          clientApiKey: request.headers.get("X-Client-Api-Key"),
          body: await request.json(),
        });
        return new Response(null, { status: 204 });
      },
    });
    let emit: ((event: TryOnExperienceEvent) => void) | undefined;
    analytics.observe((listener) => {
      emit = listener;
      return () => {
        emit = undefined;
      };
    });
    for (const operation of input.operations) {
      // oxlint-disable-next-line eslint/default-case -- Every input operation is covered.
      switch (operation.op) {
        case "event": {
          emit?.(operation.event);
          break;
        }
        case "entrypointImpression": {
          analytics.entrypointImpression(operation.productId, operation.entry);
          break;
        }
        case "cartItemAdded":
        case "orderPlaced": {
          analytics[operation.op]({
            productId: operation.productId,
            foreignIds: operation.foreignIds,
          });
          break;
        }
        case "experimentAssigned": {
          analytics.experimentAssigned(operation.enabled);
          break;
        }
        case "enabled": {
          ({ value: enabled } = operation);
          break;
        }
      }
      // oxlint-disable-next-line eslint/no-await-in-loop -- Each delivery finishes before the next input, as in the Flutter check.
      await settle();
    }
    analytics.dispose();
    const document = { comment: "Generated by sdks/core-rs/test/analytics-parity.test.ts.", sent };
    if (process.env.UPDATE_ANALYTICS_PARITY === "1") {
      await writeFile(`${parity}/expected.json`, `${JSON.stringify(document, null, 2)}\n`);
    }
    const expected = JSON.parse(await readFile(`${parity}/expected.json`, "utf8")) as unknown;
    expect(document).toEqual(expected);
  });
});
